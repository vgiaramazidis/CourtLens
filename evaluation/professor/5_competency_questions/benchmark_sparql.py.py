def sparql_results_to_df(results_json):
    """Parses JSON SPARQL results into a Pandas DataFrame."""
    vars_ = results_json["head"]["vars"]
    rows = []
    for binding in results_json["results"]["bindings"]:
        row = {}
        for var in vars_:
            row[var] = binding.get(var, {}).get("value", None)
        rows.append(row)
    return pd.DataFrame(rows, columns=vars_)


def execute_and_benchmark(endpoint_url, queries, num_runs=5):
    """Executes each SPARQL query multiple times, collects execution timings,

    and saves both the query results and execution metrics.
    """
    sparql = SPARQLWrapper(endpoint_url)
    sparql.setReturnFormat(JSON)

    metrics_summary = []

    for query_id, query_str in queries.items():
        print(f"\n--- Running {query_id} ({num_runs} iterations) ---")
        execution_times = []
        last_df = None

        for run in range(1, num_runs + 1):
            sparql.setQuery(query_str)
            start_time = time.perf_counter()

            try:
                raw_response = sparql.query().convert()
                end_time = time.perf_counter()
                elapsed_time = end_time - start_time

                execution_times.append(elapsed_time)
                print(f"  Run {run}/{num_runs}: {elapsed_time:.4f} seconds")

                # Store the DataFrame on the last iteration
                if run == num_runs:
                    last_df = sparql_results_to_df(raw_response)

            except Exception as e:
                print(f"  Run {run}/{num_runs} failed: {e}")

        # Calculate metrics if at least one run succeeded
        if execution_times:
            avg_time = statistics.mean(execution_times)
            median_time = statistics.median(execution_times)
            min_time = min(execution_times)
            max_time = max(execution_times)
            std_dev = (
                statistics.stdev(execution_times)
                if len(execution_times) > 1
                else 0.0
            )

            metrics_summary.append(
                {
                    "Query_ID": query_id,
                    "Total_Runs": len(execution_times),
                    "Avg_Time_Sec": round(avg_time, 4),
                    "Median_Time_Sec": round(median_time, 4),
                    "Min_Time_Sec": round(min_time, 4),
                    "Max_Time_Sec": round(max_time, 4),
                    "Std_Dev_Sec": round(std_dev, 4),
                    "Result_Row_Count": len(last_df)
                    if last_df is not None
                    else 0,
                }
            )

            # Save query execution output to CSV
            if last_df is not None:
                df_filename = os.path.join(
                    OUTPUT_DIR, f"{query_id}_results.csv"
                )
                last_df.to_csv(df_filename, index=False)
                print(
                    f"Saved results for {query_id} ({len(last_df)} rows) -> {df_filename}"
                )

    # Save overall execution benchmark summary
    summary_df = pd.DataFrame(metrics_summary)
    metrics_filename = os.path.join(OUTPUT_DIR, "execution_metrics.csv")
    summary_df.to_csv(metrics_filename, index=False)

    print("\n" + "=" * 60)
    print("Execution Metrics Summary")
    print("=" * 60)
    print(summary_df.to_string(index=False))
    print(f"\nExecution summary saved -> {metrics_filename}")


